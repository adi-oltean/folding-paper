"""make_results.py -- assembles WITNESS-RESULTS.md from out/witness.txt (the artifact
run_e2.sh just produced).  Run via ./run_e2.sh, not directly, though `python3
make_results.py` alone works too as long as out/witness.txt already exists.

The tables and the summary counts below are quoted VERBATIM out of out/witness.txt --
nothing here is retyped by hand from a prior run.  The prose (claim, scope, what "exact"
means) is authored, same as E0-RESULTS.md's / E1-RESULTS.md's own convention; it does not
encode any number.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))


def read(name):
    with open(os.path.join(HERE, 'out', name)) as fh:
        return fh.read()


def main():
    body = read('witness.txt')
    rc = read('witness.rc').strip()

    out = []
    out.append('# E2 -- exact folds are self-witnessing')
    out.append('')
    out.append('Generated by `run_e2.sh` (which runs `witness.py` and then calls '
                '`make_results.py`). Do not hand-edit: re-run `./run_e2.sh` from this '
                'directory instead.')
    out.append('')
    out.append('Design: `research/E2-E3-design.md` ("E2 -- exact folds are self-witnessing"). '
                'Claim under test: `research/folding-witnesses-and-learning.md`, '
                '"Why folding is unusually well-suited to the witness side" -- for a '
                'BIJECTIVE fold, over- and under-approximation coincide on the folded '
                'variable, so the fold\'s inverse is a witness generator, no separate '
                'symbolic-execution engine. `eval/refanalyzer.py` and `eval/examples.py` '
                'are imported UNCHANGED; no new fact kind, no new IR opcode.')
    out.append('')
    out.append('## Summary')
    out.append('')
    out.append('Three E0 catalogue patterns are exact (bijective) folds: affine induction '
                'variable (#1), ZigZag bijective transport (#13), lockstep elimination '
                '(#16). For each, on the E0-supplied mutant (same fact, broken check):')
    out.append('')
    out.append('1. Read the folded coordinate\'s failing value off the WITH-FACT abstract '
                'state at the check.')
    out.append('2. Invert the fold\'s closed form to a concrete input (affine: '
                '`i = s*j + c0`; ZigZag: `x = z/2`; lockstep: `i = (p - base)/s`).')
    out.append('3. Run `refanalyzer.Concrete` -- the exhaustive concrete interpreter -- on '
                'the recovered input and confirm it is reachable and genuinely violates the '
                'check.')
    out.append('4. Contrast: apply the identical inversion recipe to the SAME mutant\'s '
                'baseline (no-fact) alarm, and show it produces no witness -- the baseline '
                'interval is not exact (or the recovered candidate falls outside the '
                'program\'s own input domain), so the alarm is real but the "witness" it '
                'would naively yield is not.')
    out.append('')
    if rc == '0':
        out.append('**Result: 3/3 exact-fold witnesses confirmed by the concrete '
                    'interpreter; 3/3 contrast cases show the baseline alarm yields no '
                    'witness.** All findings below are quoted verbatim from `witness.py`\'s '
                    'own harness assertions (exit code 0 -- see `out/witness.rc`).')
    else:
        out.append('**Result: harness exit code %s -- see FINDINGS below and in the raw '
                    'output; at least one inversion or contrast did not hold as expected. '
                    'Reported as-is, not fudged.**' % rc)
    out.append('')
    out.append('## Raw harness output')
    out.append('')
    out.append('```')
    out.append(body.rstrip('\n'))
    out.append('```')
    out.append('')
    out.append('## Reading the tables')
    out.append('')
    out.append('TABLE 1 is the WITH-FOLD side: the "fold interval matches the TRUE '
                'reachable hull" row cross-checks against `Concrete`\'s own exhaustive '
                'enumeration (not asserted from the paper\'s closed form) that the '
                'WITH-FACT abstract interval has zero dead-band at this point -- the same '
                'finding E0\'s TABLE 2 made with zero discrepancy for these three patterns. '
                'Given that, the boundary value used for inversion is guaranteed reachable, '
                'and steps 2-3 confirm it mechanically rather than by appeal to the lemma.')
    out.append('')
    out.append('TABLE 2 is the control: the SAME mutant, analyzed WITHOUT the fact. The '
                'verdict is still FAIL (an over-approximate alarm is cheap -- the interval '
                'is too wide, not too narrow), but the interval is not exact, so applying '
                'the same "read off the boundary, invert" recipe either lands outside the '
                'program\'s declared input domain (ZigZag: the baseline\'s wide `z` interval '
                'inverts to an `x` value the input statement never produces) or simply does '
                'not correspond to any state the concrete interpreter reaches at that point '
                '(affine IV, lockstep: the baseline interval\'s upper edge is not on the '
                'stride\'s grid of actually-visited iterations). Either way, no witness -- '
                'the point of the contrast.')
    out.append('')
    out.append('## Scope')
    out.append('')
    out.append('This demonstrates the mechanism on the three patterns whose fold is exact '
                'by construction (bijective/affine substitution). '
                '`folding-witnesses-and-learning.md` is explicit that inexact folds '
                '(convexification, residue partitioning) do NOT get this for free -- they '
                'need a real under-approximate engine (symbolic execution / BMC), with '
                'folding only shrinking the space that engine searches. That is out of '
                'scope here by design, not by omission.')
    out.append('')

    text = '\n'.join(out) + '\n'
    with open(os.path.join(HERE, 'WITNESS-RESULTS.md'), 'w') as fh:
        fh.write(text)
    print('wrote WITNESS-RESULTS.md (%d bytes)' % len(text))


if __name__ == '__main__':
    main()
