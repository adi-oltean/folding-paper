"""make_results.py -- assemble E0-RESULTS.md from the artifacts run_e0.sh produced.

Reads only out/*.txt, out/*.rc and out/precision.json.  Every number in the generated table
comes from a run; nothing here re-derives a verdict.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out')
DOC = os.path.join(HERE, 'E0-RESULTS.md')


def read(name):
    p = os.path.join(OUT, name)
    if not os.path.exists(p):
        return ''
    with open(p) as fh:
        return fh.read()


def lines(name):
    return [ln.rstrip('\n') for ln in read(name).splitlines()]


def rc(name):
    t = read(name).strip()
    return t if t else '?'


def kv(line):
    d = {}
    for tok in line.split()[1:]:
        if '=' in tok:
            k, v = tok.split('=', 1)
            d[k] = v
    return d


def results(name, **want):
    out = []
    for ln in lines(name):
        if not ln.startswith('RESULT '):
            continue
        d = kv(ln)
        if all(d.get(k) == v for k, v in want.items()):
            out.append(d)
    return out


def first(name, **want):
    r = results(name, **want)
    return r[0] if r else {}


def aggregate(name, without, **want):
    """The per-case RESULT line, i.e. the one that carries no per-suite/per-config key."""
    for d in results(name, **want):
        if without not in d:
            return d
    return {}


def grep(name, prefix):
    for ln in lines(name):
        if ln.startswith(prefix):
            return ln
    return ''


def commas(x):
    try:
        return '{:,}'.format(int(x))
    except (TypeError, ValueError):
        return str(x)


def iv(e):
    if e is None or e.get('interval') is None:
        return 'bottom'
    return '[%s, %s]' % (commas(e['interval'][0]), commas(e['interval'][1]))


