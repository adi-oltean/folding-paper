    A('never assumed -- including when the thing doing the assuming is the proposer.')
    A('')
    A('**C5 -- case 2\'s check is vacuous at `k = n - 1`.** With the input range equal to the')
    A('whole signed analog type, `z < 2^(k+1)` is just `z < 2^n`, which the declared width')
    A('gives away. Rows `n16-k15` and `n8-k7` show both forms PROVEN for that reason and')
    A('should not be read as agreement. The reportable rows are the non-vacuous ones.')
    A('')
    A('**C6 -- case 3\'s IR model is deliberately generous to the original.** Memory is not')
    A('modelled, so each `addr[idx]` fetch is a fresh nondeterministic `input` over the word')
    A('range, and `__ffs(val)` is handed its exact range `[0, BITS-1]` as an `input` rather')
    A('than being analysed. Both concessions help the original; the original still FAILs the')
    A('pre-`min` diagnostic and still needs the clamp.')
    A('')
    A('**C7 -- what the equivalence checkers prove is C-abstract-machine equality of')
    A('results.** Original and twin are compiled in one translation unit at `-O2`; the')
    A('drivers compare returned values, not object code, and no undefined behaviour is')
    A('exercised (the twin\'s `-(value + 1)` is well defined at `INT64_MIN`, and `__ffs` is')
    A('only reached under `if (val)` in both forms). Equality of *observable results* is what')
    A('the coupling relation claims and what is checked.')
    A('')
    A('**C8 -- the IR transliterations are themselves cross-checked.** `precision.py` runs')
    A('refanalyzer\'s concrete interpreter over every IR encoding and compares it against an')
