    A('all %s. Without this, a favourable precision verdict could come from a mis-transcribed'
      % ('passing' if prec.get('selftests_all_ok') else '**NOT** passing'))
    A('program rather than from the program.')
    A('')
    A('**C9 -- no automation, no SMT, no production analyzer.** E0 verifies three')
    A('hand-recorded proposals by enumeration and measures one reference analyzer. It says')
    A('nothing about scaling the checker to SMT, about loops needing nontrivial coupling')
    A('invariants (all three relations here are input-output equality), or about automating')
    A('the propose -> verify -> analyze loop.')
    A('')

