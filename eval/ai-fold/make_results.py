    A('  the range precondition `x < 2^n`, so it is not a syntactic lowering.')
    A('')
    A('The two lowerings have identical *concrete* semantics; they differ only in which')
    A('abstract transfer the front end picks, and each is applied identically to a case\'s')
    A('original and twin. Casts (`(unsigned short)x`) are truncation, not a bitwise')
    A('operator, and lower to `modc` under both.')
